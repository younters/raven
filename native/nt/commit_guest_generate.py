# Regenerate from the retained upstream bytecode: python3 -m pip install capstone; python3 native/nt/commit_guest_generate.py
from pathlib import Path
import re,capstone,subprocess
s=Path('native/nt/providers.cpp').read_text()
md=capstone.Cs(capstone.CS_ARCH_X86,capstone.CS_MODE_64);md.detail=True
release=bytes.fromhex('49 c7 82 08 0d 00 00 00 00 00 00')
# Preserve RAX; an exchange is the shared host/guest lock's acquire operation.
acquire=bytes.fromhex('50 b8 01 00 00 00 49 87 82 08 0d 00 00 48 85 c0 58 0f 85')+bytes(4)
result=[]; offsets=[]
for name,nt in [('commit_prelude',False),('decommit_prelude',False),('nt_commit_prelude',True),('nt_decommit_prelude',True)]:
 start=re.search(r'static [^\n]*\b'+name+r'\(',s).start(); start=s.index('code{',start)+5; end=s.index('};',start)
 raw=bytes(int(v,0) for v in re.findall(r'0x[0-9a-fA-F]+|\b[0-9]+\b', re.sub(r'//[^\n]*','',s[start:end])))
 ins=list(md.disasm(raw,0));assert sum(i.size for i in ins)==len(raw)
 trap=len(raw)-5 if nt else (37 if name=='commit_prelude' else 31)
 entry=ins[3].address # after the first null-pointer conditional jump
 mapped={};out=bytearray();fix=[];acqfix=None;trapnew=None
 for i in ins:
  mapped[i.address]=len(out)
  if i.address==entry:
   out+=acquire;acqfix=len(out)-4
  if i.address==trap or i.mnemonic=='ret': out+=release
  if i.address==trap:
   trapnew=len(out);out+=b'\xe9'+bytes(4);continue
  if i.group(capstone.CS_GRP_JUMP):
   target=i.operands[0].imm
   if i.mnemonic=='jmp': out+=b'\xe9';fix.append((len(out),target,i.address));out+=bytes(4)
   else:
    cond=i.bytes[0]&15 if i.bytes[0]!=15 else i.bytes[1]&15
    out+=bytes([15,128+cond]);fix.append((len(out),target,i.address));out+=bytes(4)
  else: out+=i.bytes
 for at,target,source in fix:

  # Pointer-null entry never acquired the lock: skip the release instruction.
  dest=trapnew if source==ins[2].address else mapped[target]
  out[at:at+4]=(dest-at-4).to_bytes(4,'little',signed=True)
 out[acqfix:acqfix+4]=(trapnew-acqfix-4).to_bytes(4,'little',signed=True)
 offsets.append(trapnew)
 result.append('static const std::vector<uint8_t> '+name+'_locked{\n'+''.join('\t'+','.join('0x%02x'%v for v in out[j:j+20])+',\n' for j in range(0,len(out),20))+'};\n')
 print(name,len(raw),len(out),trapnew)
Path('native/nt/commit_guest.inc').write_text('// Generated by commit_guest_generate.py; original instruction streams retained in providers.cpp.\n'+''.join(result))
