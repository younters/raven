#!/usr/bin/env python3
"""Turns the read-only data of an x86-64 ELF object into an arm64 Mach-O assembly file of the same bytes and global labels.

native/cpu/gates.S holds code the runtime copies into its x86-64 guest and never runs itself. On Linux the host assembles it as it is;
the macOS host is arm64, so the file is assembled for x86-64 Linux and its bytes are carried over here, each label at its offset."""
import struct
import sys


def main(source, output):
    data = open(source, 'rb').read()
    if data[:4] != b'\x7fELF' or data[4] != 2 or data[5] != 1 or struct.unpack_from('<H', data, 0x12)[0] != 62:
        raise SystemExit(f'{source}: not a little-endian x86-64 ELF object')
    section_offset, = struct.unpack_from('<Q', data, 0x28)
    entry_size, count, names_index = struct.unpack_from('<HHH', data, 0x3a)
    sections = [struct.unpack_from('<IIQQQQIIQQ', data, section_offset + index * entry_size) for index in range(count)]
    names = sections[names_index]

    def name(table, offset):
        start = table[4] + offset
        return data[start:data.index(b'\0', start)].decode()

    named = {name(names, section[0]): (index, section) for index, section in enumerate(sections)}
    if any(name(names, section[0]).startswith('.rela') for section in sections):
        raise SystemExit(f'{source}: relocations cannot be carried over')
    rodata_index, rodata = named['.rodata']
    _, symbols = named['.symtab']
    strings = sections[symbols[6]]
    labels = {}
    for at in range(symbols[4], symbols[4] + symbols[5], 24):
        symbol_name, info, _, section, value, _ = struct.unpack_from('<IBBHQQ', data, at)
        if info >> 4 == 1 and section == rodata_index:
            labels.setdefault(value, []).append(name(strings, symbol_name))
    body = data[rodata[4]:rodata[4] + rodata[5]]
    alignment = max(rodata[8], 1).bit_length() - 1
    lines = [f'// Generated by guest_bytes.py from {source.split("/")[-1]}; the bytes are x86-64 code for the guest.',
             '\t.section __TEXT,__const', f'\t.p2align {alignment}']
    for value in sorted(labels):
        for label in labels[value]:
            lines.append(f'\t.globl _{label}')
    for offset in range(len(body) + 1):
        for label in labels.get(offset, []):
            lines.append(f'_{label}:')
        if offset < len(body) and (offset % 16 == 0):
            chunk = body[offset:offset + 16]
            ends = [value for value in labels if offset < value < offset + 16]
            if ends:
                chunk = body[offset:min(ends)]
            lines.append('\t.byte ' + ', '.join(str(byte) for byte in chunk))
        elif offset < len(body) and offset in labels:
            ends = [value for value in labels if offset < value < (offset // 16 + 1) * 16]
            lines.append('\t.byte ' + ', '.join(str(byte) for byte in body[offset:min(ends + [(offset // 16 + 1) * 16, len(body)])]))
    open(output, 'w').write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
