#!/usr/bin/env python3
"""Lists the number of argument words each handler of the native API registry takes.

A 32-bit program calls the same handlers with stdcall arguments, and the export tables the runtime builds for it need the count before
the registry exists. The counts are the ones the handlers are registered with.

usage: generate-registry-words.py OUTPUT.inc SOURCE.cpp ...
"""

import re
import sys

pattern = re.compile(r'registry\.add\(\s*"(\w+)"\s*,\s*(\d+)\s*,')
# Handlers registered once per character set: registry.add("Name" + suffix, N, ...) inside a loop over "W" and "A".
suffixed = re.compile(r'registry\.add\(\s*"(\w+)"\s*\+\s*suffix\s*,\s*(\d+)\s*,')

# The ANSI and wide variants also register through a conditional expression.
conditional = re.compile(r'registry\.add\(\s*\w+\s*\?\s*"(\w+)"\s*:\s*"(\w+)"\s*,\s*(\d+)\s*,')


def main():
    words = {}
    for path in sys.argv[2:]:
        text = open(path).read()
        for name, count in pattern.findall(text):
            words.setdefault(name, count)
        for first, second, count in conditional.findall(text):
            words.setdefault(first, count)
            words.setdefault(second, count)
        for name, count in suffixed.findall(text):
            for suffix in ("A", "W"):
                words.setdefault(name + suffix, count)
    with open(sys.argv[1], "w") as out:
        out.write("// Generated by scripts/generate-registry-words.py; do not edit.\n")
        for name in sorted(words):
            out.write(f'{{"{name}", {words[name]}}},\n')


if __name__ == "__main__":
    main()
